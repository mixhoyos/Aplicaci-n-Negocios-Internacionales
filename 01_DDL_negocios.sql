-- =====================================================
-- DDL NEGOCIOS INTERNACIONALES
-- Estructura de la base académica del pregrado (las mismas tablas de Contaduría Pública).
--
-- IMPORTANTE: este archivo es DOCUMENTAL. Las tablas ya existen en la base desde el
-- proyecto de Contaduría, así que NO se debe volver a ejecutar completo.
-- Aquí quedan escritas con todas las correcciones que se les hicieron después
-- (CHECK con UPPER, tamaños de columnas) y con el único cambio hecho para
-- Negocios Internacionales: la columna pf_nombre en PROFESOR (ver el final).
-- =====================================================

-- Modelo en estrella:
--   KARDEX = tabla de hechos (una fila = un estudiante, en una asignatura, con un profesor, en un semestre)
--   PROFESOR, ESTUDIANTE, ASIGNATURA = dimensiones del kardex
--   PLAN y PROGRAMA = dimensiones de estudiante y asignatura


-- ------------------------- PROFESOR -------------------------
CREATE TABLE profesor(
    pf_id_profesores          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    pf_tipo_contrato          VARCHAR2(20) NOT NULL,
    pf_escalafon              VARCHAR2(20) NOT NULL,
    pf_categoria_minciencias  VARCHAR2(20),
    pf_titulo_profesional     VARCHAR2(50) NOT NULL,
    pf_maximo_titulo          VARCHAR2(75) NOT NULL,
    pf_fecha_ingreso          DATE NOT NULL,
    pf_fecha_sabatico         DATE,
    fecha_retiro              DATE,
    pf_estado                 VARCHAR2(20) NOT NULL,

    CONSTRAINT pk_id_profesores PRIMARY KEY (pf_id_profesores),

    CONSTRAINT ck_tipo_contrato_profesores CHECK (
        UPPER(pf_tipo_contrato) IN ('TIEMPO COMPLETO', 'MEDIO TIEMPO', 'CÁTEDRA')),

    CONSTRAINT ck_escalafon_profesores CHECK (
        UPPER(pf_escalafon) IN ('AUXILIAR', 'AUXILIAR 1', 'AUXILIAR 2', 'ASISTENTE', 'ASISTENTE 1',
                                'ASISTENTE 2', 'ASOCIADO', 'TITULAR', 'DISTINGUIDO', 'I', 'II', 'III',
                                'TITULAR 1', 'TITULAR 2', 'TITULAR 3')),

    CONSTRAINT ck_categoria_minciencias CHECK (
        UPPER(pf_categoria_minciencias) IN ('JUNIOR', 'ASOCIADO', 'SENIOR', 'EMÉRITO')),

    CONSTRAINT ck_estado_profesores CHECK (
        UPPER(pf_estado) IN ('ACTIVO', 'SABÁTICO', 'RETIRADO', 'LICENCIA'))
);

-- --------------------------- PLAN ---------------------------
CREATE TABLE plan(
    p_id_planes                     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    p_resolucion_ministerio         VARCHAR2(100) NOT NULL,
    p_fecha_radicacion              DATE NOT NULL,
    p_fecha_entrada_vigencia        DATE NOT NULL,
    p_creditos_disciplinares        NUMBER NOT NULL,
    p_creditos_interdisciplinares   NUMBER NOT NULL,
    p_creditos_tronco_comun         NUMBER NOT NULL,
    p_creditos_flexibles            NUMBER NOT NULL,
    p_creditos_practica             NUMBER NOT NULL,
    p_creditos_nucleo_institucional NUMBER NOT NULL,
    p_creditos_total                NUMBER NOT NULL,
    p_estado                        VARCHAR2(20) NOT NULL,

    CONSTRAINT pk_id_planes PRIMARY KEY (p_id_planes),
    CONSTRAINT ck_estado_planes CHECK (p_estado IN ('VIGENTE', 'NO VIGENTE'))
);

-- ------------------------- PROGRAMA -------------------------
CREATE TABLE programa(
    pr_id_programas NUMBER GENERATED BY DEFAULT AS IDENTITY,
    pr_nombre       VARCHAR2(50) NOT NULL,
    pr_escuela      VARCHAR2(50) NOT NULL,
    pr_creditos     NUMBER NOT NULL,

    CONSTRAINT pk_id_programas PRIMARY KEY (pr_id_programas),
    CONSTRAINT ck_escuela_programas CHECK (pr_escuela IN (
        'artes y humanidades', 'derecho', 'finanzas, economía y gobierno',
        'administración', 'ciencias aplicadas e ingeniería'))
);

-- ------------------------ ESTUDIANTE ------------------------
CREATE TABLE estudiante (
    e_id_estudiantes                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    e_id_planes                     NUMBER NOT NULL,
    e_fecha_ingreso                 DATE NOT NULL,
    e_genero_estudiantes            VARCHAR2(100) NOT NULL,
    e_colegio                       VARCHAR2(200) NOT NULL,
    e_estrato_vivienda_origen       NUMBER NOT NULL,
    e_ciudad_origen                 VARCHAR2(100) NOT NULL,
    e_estrato_vivienda_residencia   NUMBER NOT NULL,
    e_ciudad_residencia             VARCHAR2(100) NOT NULL,
    e_saber_once                    NUMBER NOT NULL,
    e_saber_pro                     NUMBER,
    e_beca                          VARCHAR2(200),
    e_padres_profesionales          VARCHAR2(5) NOT NULL,
    e_promedio_acumulado            NUMBER(3,2) NOT NULL,
    e_promedio_semestre             NUMBER(3,2) NOT NULL,
    e_id_programa                   NUMBER,
    e_empresa_practica              VARCHAR2(200),
    e_estado                        VARCHAR2(50),

    CONSTRAINT pk_id_estudiantes PRIMARY KEY (e_id_estudiantes),
    CONSTRAINT fk_estudiantes_planes FOREIGN KEY (e_id_planes) REFERENCES plan (p_id_planes),
    CONSTRAINT fk_estudiantes_programa FOREIGN KEY (e_id_programa) REFERENCES programa (pr_id_programas),
    CONSTRAINT ck_estrato_origen_estudiantes CHECK (e_estrato_vivienda_origen BETWEEN 1 AND 6),
    CONSTRAINT ck_estrato_residencia_estudiantes CHECK (e_estrato_vivienda_residencia BETWEEN 1 AND 6),
    CONSTRAINT ck_promedio_acumulado_estudiantes CHECK (e_promedio_acumulado BETWEEN 0 AND 5),
    CONSTRAINT ck_promedio_semestre_estudiantes CHECK (e_promedio_semestre BETWEEN 0 AND 5),
    CONSTRAINT ck_genero_estudiantes CHECK (e_genero_estudiantes IN
        ('femenino', 'masculino', 'no binario', 'transexual', 'transgénero')),
    CONSTRAINT ck_padres_profesionales_estudiantes CHECK (e_padres_profesionales IN ('Sí', 'No')),
    CONSTRAINT ck_estado_estado_estudiantes CHECK (e_estado IN
        ('Matriculado', 'No matriculado', 'Graduado', 'retirado', 'suspendido', 'expulsión'))
);

-- ------------------------ ASIGNATURA ------------------------
CREATE TABLE asignatura(
    a_id_asignaturas    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    a_id_planes         NUMBER NOT NULL,
    a_nombre            VARCHAR2(100) NOT NULL,     -- ampliado de 20 a 100
    a_numero_creditos   NUMBER NOT NULL,
    a_tipologia         VARCHAR2(30) NOT NULL,      -- ampliado de 20 a 30
    a_estado            VARCHAR2(10) NOT NULL,

    CONSTRAINT pk_id_asignatura PRIMARY KEY (a_id_asignaturas),
    CONSTRAINT fk_asignatura_plan FOREIGN KEY (a_id_planes) REFERENCES plan (p_id_planes),
    -- Ojo: los valores van SIN tilde ('NUCLEO INSTITUCIONAL', 'PRACTICA')
    CONSTRAINT ck_tipologia_asignatura CHECK (a_tipologia IN
        ('TRONCO COMÚN', 'DISCIPLINAR', 'INTERDISCIPLINAR', 'FLEXIBLE', 'PRACTICA', 'NUCLEO INSTITUCIONAL')),
    CONSTRAINT ck_estado_asignatura CHECK (a_estado IN ('VIGENTE', 'NO VIGENTE'))
);

-- -------------------- KARDEX (tabla de hechos) --------------------
CREATE TABLE kardex(
    k_id_kardex         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    k_semestre          NUMBER NOT NULL,
    k_id_estudiantes    NUMBER NOT NULL,
    k_id_asignaturas    NUMBER NOT NULL,
    k_id_profesores     NUMBER NOT NULL,
    k_notas             NUMBER(3,2) DEFAULT 0.0,
    k_estado            VARCHAR2(10) NOT NULL,

    CONSTRAINT pk_id_kardex PRIMARY KEY (k_id_kardex),
    CONSTRAINT fk_estudiante_kardex FOREIGN KEY (k_id_estudiantes) REFERENCES estudiante (e_id_estudiantes),
    CONSTRAINT fk_asignatura_kardex FOREIGN KEY (k_id_asignaturas) REFERENCES asignatura (a_id_asignaturas),
    CONSTRAINT fk_profesor_kardex FOREIGN KEY (k_id_profesores) REFERENCES profesor (pf_id_profesores),
    CONSTRAINT ck_estado_kardex CHECK (k_estado IN
        ('APROBADA', 'PENDIENTE', 'CANCELADA', 'REPROBADA', 'EN CURSO', 'HOMOLOGADA'))
);


